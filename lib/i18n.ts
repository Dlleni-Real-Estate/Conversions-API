export function stageLabel(status: Status, lang: Lang): string {
  const s = STAGE_BY_STATUS[status];
  if (!s) return status;
  return lang === "ar" ? s.labelAr : s.label;
}

export function stageHint(status: Status, lang: Lang): string | undefined {
  const s = STAGE_BY_STATUS[status];
  if (!s) return undefined;
  return lang === "ar" ? (s.hintAr ?? s.hint) : s.hint;
}
